const char *statusToString(Status s) {
  switch (s) {
    case Status::Live:
      return "live";
    case Status::Scheduled:
      return "scheduled";
    case Status::Skipped:
      return "skipped";
    case Status::Unknown:
    default:
      return "unknown";
  }
}

// DESIGN.md SS7's Arrival object shape.
void serializeArrival(const Arrival &a, JsonObject o, transit::Epoch now) {
  o["trip"] = a.trip;
  o["vehicle"] = a.vehicle;
  o["destination"] = a.destination;
  o["predicted"] = a.predicted;
  o["scheduled"] = a.scheduled;
  o["eta_s"] = a.effective() > 0 ? (a.effective() - now) : 0;
  o["late_min"] = a.late_min;
  o["late_known"] = a.late_known;
  o["status"] = statusToString(a.status);
  o["seats"] = a.seats;
  o["sched_trip"] = a.sched_trip;  // matched static-schedule trip id, "" when unmatched (DESIGN.md SS7)
}

// transit::Health as the wire token GET /api/state uses (model.h, DESIGN.md SS4.7/SS7).
const char *healthToString(transit::Health h) {
  switch (h) {
    case transit::Health::Live:
      return "live";
    case transit::Health::ScheduleOnly:
      return "schedule_only";
    case transit::Health::Stale:
      return "stale";
    case transit::Health::Unavailable:
    default:
      return "unavailable";
  }
}

void serializeSnapshot(const Snapshot &snap, JsonObject out) {
  transit::Epoch now = (transit::Epoch)time(nullptr);
  // The web UI titles each panel from these config fields, so echo them next to the live data.
  Config cfg = getActiveConfig();
  JsonArray stops = out["stops"].to<JsonArray>();
  for (const StopSnapshot &s : snap.stops) {
    JsonObject so = stops.add<JsonObject>();
    so["key"] = s.key;
    for (const transit::StopConfig &sc : cfg.stops) {
      if (sc.key != s.key) continue;
      so["mode"] = sc.mode == transit::Mode::Rail ? "rail" : sc.mode == transit::Mode::Subway ? "subway" : sc.mode == transit::Mode::Trolley ? "trolley" : "bus";
      so["route"] = sc.route;
      so["stop_id"] = sc.stop_id;
      so["station"] = sc.station;
      so["direction"] = sc.direction;
      so["headsign"] = sc.headsign;
      so["label"] = sc.label;
      so["stop_name"] = sc.stop_name;
      so["show"] = sc.show;
      break;
    }
    so["ok"] = s.ok;
    so["error"] = s.error;
    so["health"] = healthToString(s.health);
    so["source_ts"] = s.source_ts;  // when SEPTA produced the data; 0 = the feed carried no timestamp
    so["source_age_s"] = s.source_ts > 0 ? (int64_t)(now - s.source_ts) : (int64_t)-1;
    so["weather_note"] = stopWeatherNote(s.key, s.arrivals.empty() ? 0 : s.arrivals.front().effective());
    JsonArray arrivals = so["arrivals"].to<JsonArray>();
    for (const Arrival &a : s.arrivals) {
      serializeArrival(a, arrivals.add<JsonObject>(), now);
    }
  }
  // DESIGN.md SS4.8/SS7: the main location's conditions plus the hourly slots the notes use.
  WeatherView wv = getWeather();
  JsonObject weather = out["weather"].to<JsonObject>();
  weather["enabled"] = cfg.weather.enabled;  // the config, not the last poll: a save applies at once
  weather["units"] = wv.fahrenheit ? "f" : "c";
  weather["age_s"] = wv.age_s;  // main location's last SUCCESS, millis-based, -1 = never (F29)
  weather["stale"] = wv.stale;  // over 60 min old: the device suppresses the header icon and notes
  if (cfg.weather.enabled && wv.main.valid()) {
    JsonObject m = weather["main"].to<JsonObject>();
    m["temp"] = wv.main.temp;
    m["feels_like"] = wv.main.feels_like;
    m["code"] = wv.main.code;
    m["text"] = weather::codeText(wv.main.code);
    m["wind"] = wv.main.wind;
    JsonArray hours = m["hours"].to<JsonArray>();
    for (const weather::Hour &h : wv.main.hours) {
      JsonObject ho = hours.add<JsonObject>();
      ho["t"] = h.epoch;
      ho["code"] = h.code;
      ho["text"] = weather::codeText(h.code);
      ho["prob"] = h.precip_prob;
      ho["temp"] = h.temp;
    }
  }
  int prof = activeProfileIndex(cfg, (time_t)now);
  out["active_profile"] = prof >= 0 ? cfg.profiles[(size_t)prof].name : "";
  BikeView bv = getBikes();
  JsonObject bike = out["bike"].to<JsonObject>();
  bike["enabled"] = cfg.bike.enabled;
  bike["age_s"] = bv.fetched_epoch > 0 ? (int64_t)now - (int64_t)bv.fetched_epoch : -1;
  JsonArray bstations = bike["stations"].to<JsonArray>();
  // In config order, with counts from the last fetch when that station was part of it; a station
  // added a moment ago shows -1 until the poller catches up rather than being missing.
  for (const BikeStation &cs : cfg.bike.stations) {
    if (!cfg.bike.enabled) break;
    indego::Station st;
    st.id = cs.id;
    st.name = cs.name;
    for (const indego::Station &f : bv.stations) {
      if (f.id == cs.id) {
        st = f;
        if (st.name.empty()) st.name = cs.name;
        break;
      }
    }
    JsonObject so = bstations.add<JsonObject>();
    so["id"] = st.id;
    so["name"] = st.name;
    so["bikes"] = st.bikes;
    so["ebikes"] = st.ebikes;
    so["classic"] = st.classic;
    so["docks"] = st.docks;
    so["total_docks"] = st.total_docks;
    so["active"] = st.active;
  }
  JsonArray alerts = out["alerts"].to<JsonArray>();
  for (const Alert &al : snap.alerts) {
    if (!cfg.alerts) break;  // the config, not the last poll
    JsonObject ao = alerts.add<JsonObject>();
    ao["route"] = al.route;
    ao["text"] = al.text;
    ao["current"] = al.current;
    JsonArray detours = ao["detours"].to<JsonArray>();
    for (const std::string &d : al.detours) {
      detours.add(d);
    }
  }
}

void sendJson(AsyncWebServerRequest *request, int code, JsonDocument &doc) {
  // Under memory pressure (several concurrent requests on a ~65 KB heap) ArduinoJson silently
  // truncates the document and String silently stays empty; both used to go out as an empty
  // HTTP 200. A 503 lets the web UI keep the last good state and try again on its next poll.
  String body;
  bool ok = !doc.overflowed() && serializeJson(doc, body) > 0 && body.length() > 0;
  if (!ok) {
    request->send(503, "application/json", "{\"error\":\"out of memory building the response, retry\"}");
    return;
  }
  request->send(code, "application/json", body);
}

void sendError(AsyncWebServerRequest *request, int code, const std::string &message, const std::string &path = "") {
  JsonDocument doc;
  doc["error"] = message;
  if (!path.empty()) {
    doc["path"] = path;
  }
  sendJson(request, code, doc);
}

