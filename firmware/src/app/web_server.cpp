// GET /api/log/<file>.csv - only "YYYY-MM.csv" is accepted (guards against path traversal /
// reading anything else off the card, DESIGN.md SS12's "same posture as a printer" notwithstanding
// - there's no reason this endpoint should ever open a file other than one of its own logs).
// AsyncWebServer streams the returned File incrementally itself; this handler just opens it.
bool isLogFilename(const std::string &name) {
  // "YYYY-MM.csv": 4 digits, '-', 2 digits, ".csv" = 11 characters.
  if (name.size() != 11 || name.compare(7, 4, ".csv") != 0) return false;
  for (size_t i = 0; i < 7; ++i) {
    if (i == 4) {
      if (name[i] != '-') return false;
    } else if (!isdigit(static_cast<unsigned char>(name[i]))) {
      return false;
    }
  }
  return true;
}

bool handleLogDownload(AsyncWebServerRequest *request) {
  std::string url = request->url().c_str();
  const std::string prefix = "/api/log/";
  if (url.rfind(prefix, 0) != 0) return false;
  std::string filename = url.substr(prefix.size());
  // PIN-protected even though it only reads (DESIGN.md SS12): the CSV is a month of the owner's
  // movements - when they leave the house and which stop they leave from - which is the most
  // personal thing this device holds. `GET /api/log/index` (file names and sizes) stays open.
  if (!requirePin(request)) return true;
  if (!isLogFilename(filename)) {
    sendError(request, 400, "not a log filename");
    return true;
  }
  // One download at a time (F26): the SD mount allows two open files and the poller's append
  // needs one of them. The export re-emits every row in schema v3 (F24/F25) through a chunked
  // response; the reader lease is released by the response's completion/disconnect callback.
  if (!acquireLogReader()) {
    sendError(request, 503, "a log download is already running, try again");
    return true;
  }
  auto exp = std::make_shared<LogExport>(filename);
  if (!exp->ok()) {
    releaseLogReader();
    sendError(request, 404, "no log for that month");
    return true;
  }
  AsyncWebServerResponse *response = request->beginChunkedResponse(
      "text/csv", [exp](uint8_t *buf, size_t maxLen, size_t /*index*/) -> size_t {
        // Runs on the AsyncTCP task, outside guarded(); LogExport::fill() catches its own
        // bad_alloc, but wrap here too so no filler allocation can ever reach std::terminate.
        try {
          return exp->fill(buf, maxLen);
        } catch (const std::bad_alloc &) {
          return (size_t)0;  // ends the chunked response
        }
      });
  response->addHeader("Content-Disposition", (String("attachment; filename=\"") + filename.c_str() + "\"").c_str());
  request->onDisconnect([]() { releaseLogReader(); });
  request->send(response);
  return true;
}

