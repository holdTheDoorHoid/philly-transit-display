// DESIGN.md SS7/SS10: gzip, right content type, ETag = firmware build id (WEB_ASSETS_ETAG - a
// hash of the source assets, which is the closest stable per-build id we have without wiring a
// separate firmware build-id scheme), If-None-Match -> 304, Cache-Control max-age=3600 for the
// static assets and no-cache for "/" (its content never changes without a firmware update, but
// browsers should still re-validate it on every navigation so a stale service worker / bookmark
// doesn't hide an update the way max-age=3600 would for up to an hour).
void handleWebAsset(AsyncWebServerRequest *request, const transit_web::WebAsset &asset) {
  bool is_index = std::strcmp(asset.path, "/") == 0;

  if (request->hasHeader("If-None-Match")) {
    const AsyncWebHeader *inm = request->getHeader("If-None-Match");
    if (inm && inm->value() == transit_web::WEB_ASSETS_ETAG) {
      AsyncWebServerResponse *response = request->beginResponse(304);
      response->addHeader("ETag", transit_web::WEB_ASSETS_ETAG);
      request->send(response);
      return;
    }
  }

  AsyncWebServerResponse *response = request->beginResponse(200, asset.content_type, asset.data, asset.len);
  response->addHeader("Content-Encoding", "gzip");
  response->addHeader("ETag", transit_web::WEB_ASSETS_ETAG);
  response->addHeader("Cache-Control", is_index ? "no-cache" : "max-age=3600");
  if (is_index) {
    // Review F05, on the document that carries the app: a hostile page that frames this UI can
    // read nothing across origins, but it can bait clicks onto controls the owner cannot see.
    // Both headers say the same thing to old and new browsers. No script-src directive on
    // purpose - the Stops page loads Leaflet from a CDN (DESIGN.md SS10) and a CSP that forbids it
    // would break the map silently; the frame directives cost nothing and break nothing.
    response->addHeader("X-Frame-Options", "DENY");
    response->addHeader("Content-Security-Policy", "frame-ancestors 'none'");
    // The UI is served gzipped from PROGMEM with fixed content types; nosniff stops a browser
    // deciding for itself that one of them is something executable.
    response->addHeader("X-Content-Type-Options", "nosniff");
  }
  request->send(response);
}

