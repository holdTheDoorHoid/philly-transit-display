void startWebServer(std::function<void(bool)> onConfigChanged) {
  setHostName(getActiveConfig().device.name);

  // Runs before any handler, for every route including the static assets and the 404 (review
  // F05). Registered first so nothing can be reached without passing it.
  g_server.addMiddleware([](AsyncWebServerRequest *request, ArMiddlewareNext next) {
    if (!hostAllowed(request)) {
      sendError(request, 421, "this device is not reachable under that host name");
      return;
    }
    next();
  });

  g_server.on("/api/state", HTTP_GET, handleGetState);
  g_server.on("/api/config", HTTP_GET, handleGetConfig);
  g_server.on("/api/config", HTTP_PUT, [onConfigChanged](AsyncWebServerRequest *request, JsonVariant &json) { handlePutConfig(request, json, onConfigChanged); });
  g_server.on("/api/pin", HTTP_POST, [](AsyncWebServerRequest *request, JsonVariant &json) { handlePostPin(request, json); });
  g_server.on("/api/reboot", HTTP_POST, handlePostReboot);
  // Test hooks (DESIGN.md SS7): what the screen is doing, and a simulated touch.
  g_server.on("/api/debug/ui", HTTP_GET, [](AsyncWebServerRequest *request) {
    ui::UiDebug d = ui::debugSnapshot();
    JsonDocument doc;
    doc["page"] = d.page;
    doc["dimmed"] = d.dimmed;
    doc["brightness"] = d.brightness;
    doc["due_active"] = d.due_active;
    doc["chimes"] = d.chimes;
    doc["active_profile"] = d.active_profile;
    JsonArray shown = doc["shown_stops"].to<JsonArray>();
    for (const std::string &k : d.shown_stops) shown.add(k);
    JsonArray hidden = doc["hidden_panels"].to<JsonArray>();
    for (const std::string &k : d.hidden_panels) hidden.add(k);
    doc["ticker"] = d.ticker;
    doc["rows"] = d.rows;
    doc["header_weather"] = d.header_weather;
    doc["lv_used"] = d.lv_used;
    doc["lv_free"] = d.lv_free;
    doc["lv_max_used"] = d.lv_max_used;
    doc["hor_res"] = d.hor_res;
    doc["ver_res"] = d.ver_res;
    doc["heap"] = ESP.getFreeHeap();
    doc["largest_block"] = heap_caps_get_largest_free_block(MALLOC_CAP_8BIT);
    sendJson(request, 200, doc);
  });
  g_server.on("/api/debug/tap", HTTP_POST, [](AsyncWebServerRequest *request) {
    if (!requirePin(request)) return;  // it changes what the screen shows, so it is state-changing
    ui::requestTap();
    request->send(200, "application/json", "{\"ok\":true}");
  });
  g_server.on("/api/wifi/reset", HTTP_POST, handlePostWifiReset);

  g_server.on("/api/proxy/stops", HTTP_GET, handleProxyStops);
  g_server.on("/api/proxy/schedule", HTTP_GET, handleProxySchedule);
  g_server.on("/api/rail/stations", HTTP_GET, handleRailStations);
  startProxyWorker();

  // Registered before /api/stats: ESPAsyncWebServer matches handler URIs by prefix, so the
  // longer path has to come first or handleGetStats answers it with "stop is required".
  g_server.on("/api/stats/overview", HTTP_GET, [](AsyncWebServerRequest *request) {
    int days = request->hasParam("days") ? atoi(request->getParam("days")->value().c_str()) : 7;
    queueOverviewRequest(request, days);
  });
  g_server.on("/api/stats", HTTP_GET, handleGetStats);
  g_server.on("/api/log/index", HTTP_GET, handleLogIndex);
  // "/api/log/<file>.csv" - matched with a regex-free prefix check in onNotFound below instead of
  // a wildcard pattern, to keep the matcher simple.

  g_server.on("/api/ota", HTTP_POST, handlePostOta, handleOtaUpload);

#ifdef TRANSIT_HAVE_WEB_ASSETS
  registerWebAssets();
#else
  g_server.on("/", HTTP_GET, [](AsyncWebServerRequest *request) {
    request->send(200, "text/plain", "web UI not built into this firmware (web/build.mjs never ran) - try /api/state");
  });
#endif

  g_server.onNotFound([](AsyncWebServerRequest *request) {
    if (request->url().startsWith("/api/log/") && handleLogDownload(request)) {
      return;
    }
    request->send(404, "application/json", "{\"error\":\"not found\"}");
  });

  g_server.begin();
  log_i("web_server: listening on port 80");
}

