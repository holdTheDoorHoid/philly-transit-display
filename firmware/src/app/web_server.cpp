// GET /api/log/<file>.csv - only "YYYY-MM.csv" is accepted (guards against path traversal /
// reading anything else off the card, DESIGN.md SS12's "same posture as a printer" notwithstanding
// - there's no reason this endpoint should ever open a file other than one of its own logs).
// AsyncWebServer streams the returned File incrementally itself; this handler just opens it.
bool isLogFilename(const std::string &name) {
  // "YYYY-MM.csv": 4 digits, '-', 2 digits, ".csv" = 11 characters.
  if (name.size() != 11 || name.compare(7, 4, ".csv") != 0) return false;
  for (size_t i = 0; i < 7; ++i) {
    if (i == 4) {
      if (name[i] != '-') return false;
    } else if (!isdigit(static_cast<unsigned char>(name[i]))) {
      return false;
    }
  }
  return true;
}

bool handleLogDownload(AsyncWebServerRequest *request) {
  std::string url = request->url().c_str();
  const std::string prefix = "/api/log/";
  if (url.rfind(prefix, 0) != 0) return false;
  std::string filename = url.substr(prefix.size());
  // PIN-protected even though it only reads (DESIGN.md SS12): the CSV is a month of the owner's
  // movements - when they leave the house and which stop they leave from - which is the most
  // personal thing this device holds. `GET /api/log/index` (file names and sizes) stays open.
  if (!requirePin(request)) return true;
  if (!isLogFilename(filename)) {
    sendError(request, 400, "not a log filename");
    return true;
  }
  // One download at a time (F26): the SD mount allows two open files and the poller's append
  // needs one of them. The export re-emits every row in schema v3 (F24/F25) through a chunked
  // response; the reader lease is released by the response's completion/disconnect callback.
  if (!acquireLogReader()) {
    sendError(request, 503, "a log download is already running, try again");
    return true;
  }
  auto exp = std::make_shared<LogExport>(filename);
  if (!exp->ok()) {
    releaseLogReader();
    sendError(request, 404, "no log for that month");
    return true;
  }
  AsyncWebServerResponse *response = request->beginChunkedResponse(
      "text/csv", [exp](uint8_t *buf, size_t maxLen, size_t /*index*/) -> size_t { return exp->fill(buf, maxLen); });
  response->addHeader("Content-Disposition", (String("attachment; filename=\"") + filename.c_str() + "\"").c_str());
  request->onDisconnect([]() { releaseLogReader(); });
  request->send(response);
  return true;
}

#ifdef TRANSIT_HAVE_WEB_ASSETS
// DESIGN.md SS7/SS10: gzip, right content type, ETag = firmware build id (WEB_ASSETS_ETAG - a
// hash of the source assets, which is the closest stable per-build id we have without wiring a
// separate firmware build-id scheme), If-None-Match -> 304, Cache-Control max-age=3600 for the
// static assets and no-cache for "/" (its content never changes without a firmware update, but
// browsers should still re-validate it on every navigation so a stale service worker / bookmark
// doesn't hide an update the way max-age=3600 would for up to an hour).
void handleWebAsset(AsyncWebServerRequest *request, const transit_web::WebAsset &asset) {
  bool is_index = std::strcmp(asset.path, "/") == 0;

  if (request->hasHeader("If-None-Match")) {
    const AsyncWebHeader *inm = request->getHeader("If-None-Match");
    if (inm && inm->value() == transit_web::WEB_ASSETS_ETAG) {
      AsyncWebServerResponse *response = request->beginResponse(304);
      response->addHeader("ETag", transit_web::WEB_ASSETS_ETAG);
      request->send(response);
      return;
    }
  }

  AsyncWebServerResponse *response = request->beginResponse(200, asset.content_type, asset.data, asset.len);
  response->addHeader("Content-Encoding", "gzip");
  response->addHeader("ETag", transit_web::WEB_ASSETS_ETAG);
  response->addHeader("Cache-Control", is_index ? "no-cache" : "max-age=3600");
  if (is_index) {
    // Review F05, on the document that carries the app: a hostile page that frames this UI can
    // read nothing across origins, but it can bait clicks onto controls the owner cannot see.
    // Both headers say the same thing to old and new browsers. No script-src directive on
    // purpose - the Stops page loads Leaflet from a CDN (DESIGN.md SS10) and a CSP that forbids it
    // would break the map silently; the frame directives cost nothing and break nothing.
    response->addHeader("X-Frame-Options", "DENY");
    response->addHeader("Content-Security-Policy", "frame-ancestors 'none'");
    // The UI is served gzipped from PROGMEM with fixed content types; nosniff stops a browser
    // deciding for itself that one of them is something executable.
    response->addHeader("X-Content-Type-Options", "nosniff");
  }
  request->send(response);
}

void registerWebAssets() {
  for (size_t i = 0; i < transit_web::WEB_ASSETS_COUNT; ++i) {
    const transit_web::WebAsset &asset = transit_web::WEB_ASSETS[i];
    g_server.on(asset.path, HTTP_GET, [asset](AsyncWebServerRequest *request) { handleWebAsset(request, asset); });
  }
}
#endif  // TRANSIT_HAVE_WEB_ASSETS

